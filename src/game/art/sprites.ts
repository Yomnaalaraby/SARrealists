export function getCrewSprite(role: string): Sprite {
  return { ...SPRITES.crew, palette: { ...SPRITES.crew.palette, a: CREW_ACCENTS[role] ?? SPRITES.crew.palette.a } };
}

export function getLensSprite(lensId: string): Sprite {
  return SPRITES[`lens_${lensId}` as keyof typeof SPRITES] as Sprite;
}
